#!/usr/bin/env python3
"""
build_circuit_model.py

Purpose:
    Convert parsed netlist JSON into the normalized circuit-domain model used
    by graph and matrix tools. Creates deterministic node and branch orders.

Author: Dr. Francisco E. Rangel-Patiño
"""
from __future__ import annotations

import argparse
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any


class CircuitModelError(ValueError):
    """Raised when the parsed netlist cannot become a valid circuit model."""


@dataclass(frozen=True)
class Node:
    id: str
    index_full: int
    index_reduced: int | None
    is_reference: bool


@dataclass(frozen=True)
class Branch:
    id: str
    index: int
    component_name: str
    element_type: str
    node_from: str
    node_to: str
    value_si: float
    unit: str
    source_kind: str | None = None
    ac_magnitude: float | None = None
    ac_phase_deg: float | None = None
    source_line: str = ""
    line_number: int = 0


@dataclass
class Circuit:
    schema_version: str
    source_name: str
    reference_node: str
    nodes: list[Node] = field(default_factory=list)
    branches: list[Branch] = field(default_factory=list)
    directives: list[dict[str, Any]] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def node_sort_key(node: str) -> tuple[Any, ...]:
    if node == "0":
        return (0, 0, 0)
    if node.isdigit():
        return (1, 0, int(node))
    return (1, 1, node.lower())


def build_circuit(parsed: dict[str, Any]) -> Circuit:
    """Build a deterministic domain model from parsed netlist data."""
    elements = parsed.get("elements", [])
    if not elements:
        raise CircuitModelError("Parsed data contains no elements")
    node_ids = sorted(
        {e["node_from"] for e in elements} | {e["node_to"] for e in elements},
        key=node_sort_key,
    )
    if "0" not in node_ids:
        raise CircuitModelError("Reference node 0/GND is required")
    nodes: list[Node] = []
    reduced_counter = 0
    for full_index, node_id in enumerate(node_ids):
        is_reference = node_id == "0"
        reduced_index = None if is_reference else reduced_counter
        if not is_reference:
            reduced_counter += 1
        nodes.append(Node(node_id, full_index, reduced_index, is_reference))

    branches: list[Branch] = []
    for index, element in enumerate(elements):
        branches.append(
            Branch(
                id=f"B{index + 1}",
                index=index,
                component_name=element["name"],
                element_type=element["type"],
                node_from=element["node_from"],
                node_to=element["node_to"],
                value_si=float(element["value_si"]),
                unit=element["unit"],
                source_kind=element.get("source_kind"),
                ac_magnitude=element.get("ac_magnitude"),
                ac_phase_deg=element.get("ac_phase_deg"),
                source_line=element.get("source_line", ""),
                line_number=int(element.get("line_number", 0)),
            )
        )
    return Circuit(
        schema_version="1.0",
        source_name=parsed.get("source_name", "<unknown>"),
        reference_node="0",
        nodes=nodes,
        branches=branches,
        directives=parsed.get("directives", []),
        warnings=parsed.get("warnings", []),
    )


def circuit_to_dict(circuit: Circuit) -> dict[str, Any]:
    return asdict(circuit)


def load_parsed(path: str | Path) -> dict[str, Any]:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def load_circuit(path: str | Path) -> Circuit:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    return Circuit(
        schema_version=data["schema_version"],
        source_name=data["source_name"],
        reference_node=data["reference_node"],
        nodes=[Node(**item) for item in data["nodes"]],
        branches=[Branch(**item) for item in data["branches"]],
        directives=data.get("directives", []),
        warnings=data.get("warnings", []),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Build a normalized circuit model")
    parser.add_argument("parsed_json", help="JSON generated by parse_netlist.py")
    parser.add_argument("-o", "--output", required=True, help="Output circuit JSON")
    args = parser.parse_args()
    circuit = build_circuit(load_parsed(args.parsed_json))
    Path(args.output).write_text(json.dumps(circuit_to_dict(circuit), indent=2), encoding="utf-8")
    print(f"Built circuit: {len(circuit.nodes)} nodes, {len(circuit.branches)} branches -> {args.output}")


if __name__ == "__main__":
    main()
